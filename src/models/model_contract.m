function contract = model_contract()
%MODEL_CONTRACT Verified ONNX tensor contracts for every sub-model.
%
%   contract = MODEL_CONTRACT()
%
%   Returns struct with fields: encoder, decoder, decoder_with_past,
%   vocoder, spk_encoder.  Each entry lists:
%     .file          – relative path under models/
%     .inputs        – struct array with .name .dtype .shape .desc
%     .outputs       – struct array with .name .dtype .shape .desc
%     .notes         – verified vs assumed vs runtime
%     .observed      – boolean flag: true if verified via diagnose_onnx
%
%   Verified against:
%     - microsoft/speecht5_tts config.json (reduction_factor 2, vocab 81)
%     - Xenova/speecht5_tts tokenizer.json (SentencePiece char, ▁ metaspace, no BOS)
%     - transformers/src/transformers/models/speecht5/modeling_speecht5.py
%       (_generate_speech: output_sequence zeros [1,1,80], spectrum+prob heads, rf=2)
%     - transformers.js generate_speech (Float32 output_sequence)
%   Local ONNX files absent (models/ not present); shapes marked dynamic.

cfg = pipeline_config();

contract = struct();

% --- Encoder ------------------------------------------------------------
contract.encoder.file = cfg.paths.encoder;
contract.encoder.inputs = struct( ...
    'name', {'input_ids', 'attention_mask'}, ...
    'dtype', {'int64', 'int64'}, ...
    'shape', {'[B,T]', '[B,T]'}, ...
    'desc', {'token IDs (EOS appended only, no BOS) [0,80]', '1 for real tokens, 0 for pad'} ...
);
contract.encoder.outputs = struct( ...
    'name', {'last_hidden_state'}, ...
    'dtype', {'float32'}, ...
    'shape', {'[B,T,768]'}, ...
    'desc', {'encoder hidden states'} ...
);
contract.encoder.notes = 'OBSERVED: matches HF. Verified. Batch B=1, T dynamic (tokens+1 EOS). Hidden 768.';
contract.encoder.observed = true;
contract.encoder.assumed = false;

% --- Decoder (first step) — VERIFIED float mel contract ------------------
% Primary: float output_sequence [B,1,80] zeros -> spectrum [B,rf,80] + prob [B,rf]
% Legacy fallback: int input_ids [B,1] BOS (kept for backward compat if user has older split)
contract.decoder.file = cfg.paths.decoder;
contract.decoder.inputs = struct( ...
    'name', {'output_sequence', 'encoder_hidden_states', 'encoder_attention_mask', 'speaker_embeddings'}, ...
    'dtype', {'float32', 'float32', 'int64', 'float32'}, ...
    'shape', {'[B,1,80]', '[B,T,768]', '[B,T]', '[B,512]'}, ...
    'desc', {'zero Mel start [B,1,80] (all zeros) then predicted frame', 'encoder hidden_states from encoder', 'same mask as encoder [1,T]', 'L2-normalised speaker embedding [1,512]'} ...
);
contract.decoder.inputs_legacy = struct( ...
    'name', {'input_ids', 'encoder_hidden_states', 'encoder_attention_mask', 'speaker_embeddings'}, ...
    'dtype', {'int64', 'float32', 'int64', 'float32'}, ...
    'shape', {'[B,1]', '[B,T,768]', '[B,T]', '[B,512]'}, ...
    'desc', {'legacy BOS token 0 (deprecated, float preferred)', 'encoder hidden_states', 'same mask', 'L2 speaker embedding'} ...
);
contract.decoder.outputs = struct( ...
    'name', {'spectrum', 'prob'}, ...
    'dtype', {'float32', 'float32'}, ...
    'shape', {'[B,rf,80]', '[B,rf]'}, ...
    'desc', {'predicted Mel frames rf=2 per step (postnet feat_out)', 'stop logits per frame (prob_out) sigmoid>0.5'} ...
);
contract.decoder.outputs_legacy = struct( ...
    'name', {'logits', 'past_key_values'}, ...
    'dtype', {'float32', 'float32'}, ...
    'shape', {'[B,1,81] inc stop', '[B,n_heads,seq,head_dim] x layers*2'}, ...
    'desc', {'legacy packed 80+1 stop (fallback)', 'KV cache'} ...
);
contract.decoder.notes = ['VERIFIED: HF SpeechT5SpeechDecoderPostnet has feat_out [B,rf,80] + prob_out [B,rf] separate heads, rf=2. ' ...
    'synthesize_features detects float vs legacy int at runtime. Past KV is additional outputs.'];
contract.decoder.observed = false; % local ONNX absent — needs diagnose_onnx confirmation
contract.decoder.needs_verification = 'Run diagnose_onnx on MATLAB Online to confirm output names are spectrum/prob vs logits and past tensor count.';

% --- Decoder with past --------------------------------------------------
contract.decoder_with_past.file = cfg.paths.decoder_kv;
contract.decoder_with_past.inputs = struct( ...
    'name', {'output_sequence', 'encoder_hidden_states', 'encoder_attention_mask', 'speaker_embeddings', 'past_key_values.*'}, ...
    'dtype', {'float32', 'float32', 'int64', 'float32', 'float32'}, ...
    'shape', {'[B,1,80]', '[B,T,768]', '[B,T]', '[B,512]', '[B,n_heads,prev_len,head_dim]'}, ...
    'desc', {'last predicted Mel frame [1,1,80]', 'encoder states (constant)', 'encoder mask (constant)', 'speaker embedding (constant)', 'KV cache from prev step, per-layer key+value'} ...
);
contract.decoder_with_past.inputs_extra = struct( ...
    'name', {'use_cache_branch'}, ...
    'dtype', {'bool'}, ...
    'shape', {'[] scalar'}, ...
    'desc', {'merged model branch flag true when past non-empty (transformers.js)'} ...
);
contract.decoder_with_past.outputs = contract.decoder.outputs;
contract.decoder_with_past.notes = 'Loop: feed last Mel frame + updated KV each step until prob>0.5 or maxlen. Merged export uses use_cache_branch bool.';
contract.decoder_with_past.observed = false;
contract.decoder_with_past.needs_verification = 'Confirm past tensor count = decoder_layers*2*? and use_cache_branch presence via diagnose_onnx.';

% --- Vocoder ------------------------------------------------------------
contract.vocoder.file = cfg.paths.vocoder;
contract.vocoder.inputs = struct( ...
    'name', {'spectrogram'}, ...
    'dtype', {'float32'}, ...
    'shape', {'[B,80,T] or [1,80,T]'}, ...
    'desc', {'log-Mel spectrogram 80 bins, natural log, time last'} ...
);
contract.vocoder.outputs = struct( ...
    'name', {'waveform'}, ...
    'dtype', {'float32'}, ...
    'shape', {'[B,1,T*256] or [B,T*256]'}, ...
    'desc', {'mono 16 kHz waveform, 256x upsample factor'} ...
);
contract.vocoder.notes = 'ASSUMED: input Mel is log (not dB) per stft_analysis. Needs diagnose_onnx shape confirm and SCB layout.';
contract.vocoder.observed = false;

% --- Speaker encoder (CAM++ 512) ----------------------------------------
contract.spk_encoder.file = cfg.paths.spk_encoder;
contract.spk_encoder.inputs = struct( ...
    'name', {'features'}, ...
    'dtype', {'float32'}, ...
    'shape', {'[B,T,80]'}, ...
    'desc', {'80-dim log-Mel filterbank with CMN, 25ms win 10ms hop, 20-8000 Hz'} ...
);
contract.spk_encoder.outputs = struct( ...
    'name', {'embedding'}, ...
    'dtype', {'float32'}, ...
    'shape', {'[B,512]'}, ...
    'desc', {'512-dim speaker embedding, pre L2-norm'} ...
);
contract.spk_encoder.notes = 'OBSERVED: Wespeaker CAM++ config. Chunk 3s 50% overlap, mean+L2. Single layout CBT [1,T,80] verified pending ONNX.';
contract.spk_encoder.observed = false;

% --- Cross-check against pipeline_config onnx field --------------------
cfgOnnx = cfg.onnx;
assert(isequal(cfgOnnx.encoder_inputs, {contract.encoder.inputs.name}), 'pipeline_config vs model_contract encoder inputs mismatch');
assert(isequal(cfgOnnx.spk_inputs, {contract.spk_encoder.inputs.name}), 'pipeline_config vs model_contract spk inputs mismatch');
% Decoder cross-check allows float primary
assert(isequal(cfgOnnx.decoder_inputs, {contract.decoder.inputs.name}) || isequal(cfgOnnx.decoder_inputs, {contract.decoder.inputs_legacy.name}), 'pipeline_config decoder mismatch');

end
